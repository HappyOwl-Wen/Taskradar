import { act, fireEvent, render } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { LiquidSelectionEffects } from "./LiquidSelectionEffects";

afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals(); });

it("glides the existing selection when its navigation changes size, and cancels it on cleanup", async () => {
  let resize!: () => void, width = 220;
  vi.stubGlobal("matchMedia", () => ({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() }));
  vi.stubGlobal("ResizeObserver", class { constructor(callback: () => void) { resize = callback; } observe() {} unobserve() {} disconnect() {} });
  vi.stubGlobal("requestAnimationFrame", (callback: FrameRequestCallback) => { callback(0); return 0; });
  vi.stubGlobal("cancelAnimationFrame", vi.fn());
  const group = document.createElement("nav"), active = document.createElement("a");
  group.dataset.selectionScope = "navigation"; active.setAttribute("aria-current", "page");
  active.style.borderRadius = "13px"; active.textContent = "Today"; group.append(active); document.body.append(group);
  const rect = () => ({ left: 0, top: 0, width, height: 44 }) as DOMRect;
  vi.spyOn(group, "getBoundingClientRect").mockImplementation(rect);
  vi.spyOn(active, "getBoundingClientRect").mockImplementation(rect);
  Object.defineProperties(group, { offsetWidth: { get: () => width }, offsetHeight: { value: 44 } });
  const mounted = render(<LiquidSelectionEffects />), lens = group.querySelector<HTMLElement>(".liquid-selection")!;
  vi.spyOn(lens, "getBoundingClientRect").mockReturnValue({ left: 0, top: 0, width: 220, height: 44 } as DOMRect);
  const cancel = vi.fn(), animate = vi.fn(() => ({ finished: new Promise(() => {}), cancel }));
  Object.defineProperty(lens, "animate", { value: animate });
  await act(async () => { width = 64; resize(); });
  expect(group.querySelectorAll(".liquid-selection")).toHaveLength(1);
  expect(group.querySelectorAll(".liquid-selection-refraction")).toHaveLength(1);
  expect(lens.querySelector(".liquid-selection-glass > .liquid-selection-rim")).not.toBeNull();
  expect(animate).toHaveBeenCalledOnce();
  const [frames] = animate.mock.calls[0] as unknown as [Keyframe[]];
  expect(frames[0].transform).toContain(`scale(${220 / 64}, 1)`);
  expect(frames.at(-1)!.transform).toContain("scale(1, 1)");
  mounted.unmount(); expect(cancel).toHaveBeenCalledOnce(); expect(group.querySelector(".liquid-selection")).toBeNull();
  expect(group.querySelector(".liquid-selection-refraction")).toBeNull();
  group.remove();
});

it("animates the selected icon once and immediately stops both animations for reduced motion", async () => {
  vi.stubGlobal("PointerEvent", MouseEvent);
  const preference = { matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() };
  vi.stubGlobal("matchMedia", () => preference);
  vi.stubGlobal("ResizeObserver", class { observe() {} unobserve() {} disconnect() {} });
  vi.stubGlobal("requestAnimationFrame", (callback: FrameRequestCallback) => { callback(0); return 0; });
  vi.stubGlobal("cancelAnimationFrame", vi.fn());
  const group = document.createElement("nav"), first = document.createElement("a"), second = document.createElement("a");
  const icon = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  group.dataset.selectionScope = "navigation"; first.setAttribute("aria-current", "page");
  first.textContent = "Today"; second.append(icon); group.append(first, second); document.body.append(group);
  const rect = (top: number) => ({ left: 0, top, width: 200, height: 44 }) as DOMRect;
  vi.spyOn(group, "getBoundingClientRect").mockReturnValue(rect(0));
  vi.spyOn(first, "getBoundingClientRect").mockReturnValue(rect(0));
  vi.spyOn(second, "getBoundingClientRect").mockReturnValue(rect(50));
  Object.defineProperties(group, { offsetWidth: { value: 200 }, offsetHeight: { value: 100 } });
  const mounted = render(<LiquidSelectionEffects />), lens = group.querySelector<HTMLElement>(".liquid-selection")!;
  vi.spyOn(lens, "getBoundingClientRect").mockReturnValue(rect(0));
  const cancelLens = vi.fn(), cancelIcon = vi.fn();
  const cancelOptics = vi.fn(), animateOptics = vi.fn(() => ({ finished: new Promise(() => {}), cancel: cancelOptics }));
  const animateLens = vi.fn(() => ({ finished: new Promise(() => {}), cancel: cancelLens }));
  const animateIcon = vi.fn(() => ({ finished: new Promise(() => {}), cancel: cancelIcon }));
  Object.defineProperty(lens, "animate", { value: animateLens });
  const refraction = group.querySelector<HTMLElement>(".liquid-selection-refraction")!;
  Object.defineProperty(refraction, "animate", { value: animateOptics });
  Object.defineProperty(icon, "animate", { value: animateIcon });
  await act(async () => { first.removeAttribute("aria-current"); second.setAttribute("aria-current", "page"); });
  expect(animateLens).toHaveBeenCalledOnce();
  expect(animateIcon).toHaveBeenCalledOnce();
  expect(animateOptics).toHaveBeenCalledOnce();
  expect(lens.dataset.motion).toBe("moving");
  fireEvent.pointerDown(second, { button: 0 });
  expect(lens.dataset.pressed).toBe("true");
  fireEvent(window, new Event("blur"));
  expect(lens.dataset.pressed).toBeUndefined();
  fireEvent.pointerDown(second, { button: 0 });
  await act(async () => { preference.matches = true; preference.addEventListener.mock.calls[0][1](); });
  expect(cancelLens).toHaveBeenCalledOnce();
  expect(cancelIcon).toHaveBeenCalledOnce();
  expect(cancelOptics).toHaveBeenCalledOnce();
  expect(lens.dataset.motion).toBe("idle");
  expect(lens.style.willChange).toBe("");
  expect(refraction.style.willChange).toBe("");
  expect(lens.dataset.pressed).toBeUndefined();
  mounted.unmount(); group.remove();
});

it("restores the resting phase after completion or cancellation and ignores an interrupted glide's completion", async () => {
  vi.stubGlobal("matchMedia", () => ({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() }));
  vi.stubGlobal("ResizeObserver", class { observe() {} unobserve() {} disconnect() {} });
  vi.stubGlobal("requestAnimationFrame", (callback: FrameRequestCallback) => { callback(0); return 0; });
  vi.stubGlobal("cancelAnimationFrame", vi.fn());
  const group = document.createElement("nav"), first = document.createElement("a"), second = document.createElement("a");
  group.dataset.selectionScope = "navigation"; first.setAttribute("aria-current", "page");
  first.textContent = "日"; second.textContent = "日程列表"; group.append(first, second); document.body.append(group);
  const rect = (left: number) => ({ left, top: 0, width: 100, height: 30 }) as DOMRect;
  vi.spyOn(group, "getBoundingClientRect").mockReturnValue({ ...rect(0), width: 200 } as DOMRect);
  vi.spyOn(first, "getBoundingClientRect").mockReturnValue(rect(0));
  vi.spyOn(second, "getBoundingClientRect").mockReturnValue(rect(100));
  Object.defineProperties(group, { offsetWidth: { value: 200 }, offsetHeight: { value: 30 } });
  const mounted = render(<LiquidSelectionEffects />), lens = group.querySelector<HTMLElement>(".liquid-selection")!;
  vi.spyOn(lens, "getBoundingClientRect").mockReturnValue(rect(0));
  const glide = () => {
    let finish!: () => void, abort!: (reason: Error) => void;
    return { finished: new Promise<void>((resolve, reject) => { finish = resolve; abort = reject; }),
      cancel: vi.fn(), finish: () => finish(), abort: () => abort(new Error("Animation cancelled")) };
  };
  const old = glide(), current = glide(), cancelled = glide();
  const oldOptics = glide(), currentOptics = glide(), cancelledOptics = glide();
  const refraction = group.querySelector<HTMLElement>(".liquid-selection-refraction")!;
  const animateOptics = vi.fn().mockReturnValueOnce(oldOptics).mockReturnValueOnce(currentOptics).mockReturnValueOnce(cancelledOptics);
  Object.defineProperty(refraction, "animate", { value: animateOptics });
  const animate = vi.fn().mockReturnValueOnce(old).mockReturnValueOnce(current).mockReturnValueOnce(cancelled);
  Object.defineProperty(lens, "animate", { value: animate });
  expect(lens.dataset.motion).toBe("idle");
  const select = async (target: HTMLElement, previous: HTMLElement) => {
    await act(async () => { previous.removeAttribute("aria-current"); target.setAttribute("aria-current", "page"); });
    expect(lens.dataset.motion).toBe("moving");
  };
  await select(second, first);
  refraction.style.opacity = ".63"; // Stand in for the in-progress compositor opacity in jsdom.
  await select(first, second);
  expect(animateOptics.mock.calls[1][0][0].opacity).toBe(.63);
  refraction.style.removeProperty("opacity");
  expect(old.cancel).toHaveBeenCalledOnce();
  expect(oldOptics.cancel).toHaveBeenCalledOnce();
  await act(async () => { old.finish(); });
  expect(lens.dataset.motion).toBe("moving");
  expect(currentOptics.cancel).not.toHaveBeenCalled();
  await act(async () => { current.finish(); });
  expect(lens.dataset.motion).toBe("idle");
  expect(lens.style.willChange).toBe("");
  expect(currentOptics.cancel).toHaveBeenCalledOnce();
  await select(second, first);
  await act(async () => { cancelled.abort(); });
  expect(lens.dataset.motion).toBe("idle");
  expect(lens.style.willChange).toBe("");
  expect(cancelledOptics.cancel).toHaveBeenCalledOnce();
  mounted.unmount(); group.remove();
});
